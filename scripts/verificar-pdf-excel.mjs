import assert from 'node:assert/strict';
import {readFile,writeFile} from 'node:fs/promises';
const source = await readFile(new URL('../src/Imoveis.Web/wwwroot/pdf-excel.js',import.meta.url),'utf8');
const {pdfWorkbook,pdfCorrections} = await import('data:text/javascript;base64,'+Buffer.from(source).toString('base64'));
const columns = [['code','Código'],['title','Título'],['kind','Tipo'],['city','Cidade'],['zone','Zona'],['price','Preço'],['notes','Observações internas']];
const original = [{exchangeId:'linha-1',page:2,text:'Texto original com acentos',selected:true,data:{code:'0001',title:'Casa & jardim',kind:'Casa',city:'São Paulo',zone:'Zona Oeste',price:'380000.00',notes:'=texto literal\nConferir proprietário'}}];
const headers = ['ID da revisão','Incluir','Página','Texto original','Origem dos códigos',...columns.map(([,label])=>label)];
const exported = [headers,['linha-1','Sim',2,original[0].text,'Catálogo',...columns.map(([key])=>original[0].data[key])]];
const bytes = pdfWorkbook(original,[{page:2,text:'Entrega prevista'}],columns,'Catálogo');
assert.equal(new DataView(bytes.buffer).getUint32(0,true),0x04034b50);
let result = pdfCorrections(exported,original,columns);
assert.deepEqual(result.rows[0].data,original[0].data);
assert.equal(result.source,'Catálogo');
assert.equal(result.rows[0].text,original[0].text);
const corrected = structuredClone(exported);
corrected[1][1]='Não';corrected[1][headers.indexOf('Preço')]=420000;
result = pdfCorrections(corrected,original,columns);
assert.equal(result.rows[0].selected,false);
assert.equal(result.rows[0].data.price,'420000');
assert.equal(result.rows[0].data.code,'0001');
// Column and row order may change; deleted rows stay out.
const reordered = corrected.map(row=>[...row].reverse());
assert.equal(pdfCorrections(reordered,[],columns).rows[0].text,original[0].text);
assert.throws(()=>pdfCorrections([['Código'],['1']],[],columns),/Mantenha as colunas/);
assert.throws(()=>pdfCorrections([...exported,exported[1]],[],columns),/ID da revisão repetido/);
const invalid = structuredClone(exported); invalid[1][1]='Talvez';
assert.throws(()=>pdfCorrections(invalid,[],columns),/Sim ou Não/);
const added = [...exported,['','Sim','','','Catálogo','0002','Apartamento','Apartamento','Cotia','Zona Oeste','250000','']];
assert.equal(pdfCorrections(added,[],columns).rows.length,2);
if(process.argv[2]) await writeFile(process.argv[2],bytes);
console.log('OK: Excel ZIP, correções, seleção, códigos com zeros, referências, colunas reordenadas e validação de cabeçalhos/IDs.');
